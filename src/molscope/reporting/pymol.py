"""Export 3D molecular visualization scripts for PyMOL and ChimeraX.

Maps MolScope feature scores (e.g. SAM-MFP Pareto rank, PCA salience, or LOFO
predictive importance) onto residue B-factors in a PDB file and generates
one-click visualization scripts.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Mapping, Sequence

import MDAnalysis as mda
import numpy as np
import pandas as pd


_RESIDUE_PATTERN = re.compile(r"__(?:X|chain_([A-Za-z0-9]+))__([A-Za-z]{3})_(\d+)")
_SIDECHAIN_PATTERN = re.compile(r"SIDECHAIN_.*?([A-Za-z]{3})_(\d+)")
_PAIR_PATTERN = re.compile(r"([A-Za-z0-9]+)__([A-Za-z]{3})_(\d+)__([A-Za-z0-9]+)__([A-Za-z]{3})_(\d+)")


def extract_residue_scores(
    feature_table: pd.DataFrame,
    feature_column: str = "Feature",
    score_column: str = "PCA_Salience",
) -> dict[int, float]:
    """Map feature-level scores to individual residue numbers.

    If multiple features map to the same residue, the maximum absolute score is retained.
    """
    if feature_column not in feature_table.columns or score_column not in feature_table.columns:
        raise ValueError(
            f"Table must contain {feature_column!r} and {score_column!r}. "
            f"Available: {list(feature_table.columns)}"
        )

    residue_scores: dict[int, float] = {}

    for _, row in feature_table.iterrows():
        name = str(row[feature_column])
        try:
            val = float(row[score_column])
        except (ValueError, TypeError):
            continue
        if not np.isfinite(val):
            continue

        # Check pair pattern first
        pair_match = _PAIR_PATTERN.search(name)
        if pair_match:
            res1 = int(pair_match.group(3))
            res2 = int(pair_match.group(6))
            for res in (res1, res2):
                residue_scores[res] = max(residue_scores.get(res, 0.0), abs(val))
            continue

        # Check sidechain pattern
        sc_match = _SIDECHAIN_PATTERN.search(name)
        if sc_match:
            res = int(sc_match.group(2))
            residue_scores[res] = max(residue_scores.get(res, 0.0), abs(val))
            continue

        # Check general residue pattern
        res_matches = _RESIDUE_PATTERN.findall(name)
        if res_matches:
            for _, _, resid_str in res_matches:
                res = int(resid_str)
                residue_scores[res] = max(residue_scores.get(res, 0.0), abs(val))

    return residue_scores


def export_3d_visualization(
    topology: str | Path,
    output_dir: str | Path,
    residue_scores: Mapping[int, float],
    basename: str = "molscope_3d",
    top_label_count: int = 8,
) -> dict[str, Path]:
    """Export a PDB with scores in B-factor column, along with PyMOL (.pml) and ChimeraX (.cxc) scripts.

    Args:
        topology: Input PDB topology.
        output_dir: Directory where outputs will be written.
        residue_scores: Mapping of residue sequence number to scalar score (0.0 - 1.0 or unnormalized).
        basename: Base name for generated files.
        top_label_count: Number of top scoring residues to highlight with labels/sticks.

    Returns:
        Dict mapping keys ('pdb', 'pymol_script', 'chimerax_script') to their output Paths.
    """
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    universe = mda.Universe(str(topology))
    if not hasattr(universe.atoms, "tempfactors"):
        universe.add_TopologyAttr("tempfactors")

    # Normalize scores to [0.0, 1.0]
    max_score = max(residue_scores.values(), default=1.0)
    if max_score <= 0.0:
        max_score = 1.0
    normalized = {res: float(np.clip(score / max_score, 0.0, 1.0)) for res, score in residue_scores.items()}

    # Assign tempfactor (B-factor) per atom based on residue number
    b_factors = np.zeros(len(universe.atoms), dtype=float)
    for i, atom in enumerate(universe.atoms):
        try:
            resnum = int(atom.resid)
            b_factors[i] = normalized.get(resnum, 0.0)
        except (ValueError, TypeError):
            b_factors[i] = 0.0

    universe.atoms.tempfactors = b_factors

    pdb_out = out_path / f"{basename}.pdb"
    pml_out = out_path / f"{basename}.pml"
    cxc_out = out_path / f"{basename}.cxc"

    universe.atoms.write(str(pdb_out))

    # Top residues for labeling
    sorted_residues = sorted(normalized.items(), key=lambda kv: kv[1], reverse=True)[:top_label_count]
    top_resids = [str(res) for res, sc in sorted_residues if sc > 0.1]
    res_selection = "+".join(top_resids) if top_resids else ""

    # Generate PyMOL script
    pml_lines = [
        "# MolScope PyMOL Visualization Script",
        "# Auto-generated by MolScope",
        "reinitialize",
        f"load {pdb_out.name}, molscope_mol",
        "hide everything, molscope_mol",
        "show cartoon, molscope_mol",
        "cartoon putty, molscope_mol",
        "spectrum b, blue_white_red, molscope_mol, minimum=0.0, maximum=1.0",
        "set cartoon_putty_scale_min, 0.3",
        "set cartoon_putty_scale_max, 1.8",
        "set cartoon_putty_transform, 0",
        "bg_color white",
        "set ray_opaque_background, 1",
    ]
    if res_selection:
        pml_lines.extend([
            f"select top_discriminators, molscope_mol and resi {res_selection}",
            "show sticks, top_discriminators and not (name c+n+o)",
            "select top_ca, top_discriminators and name CA",
            'label top_ca, "%s %s" % (resn, resi)',
            "set label_size, 14",
            "set label_color, black",
            "set label_outline_color, white",
        ])
    pml_lines.extend([
        "orient molscope_mol",
        "zoom molscope_mol, 2",
    ])
    pml_out.write_text("\n".join(pml_lines) + "\n", encoding="utf-8")

    # Generate ChimeraX script
    cxc_lines = [
        "# MolScope ChimeraX Visualization Script",
        f"open {pdb_out.name}",
        "hide atoms",
        "show cartoon",
        "color bfactor palette blue:white:red range 0.0,1.0",
        "cartoon style mode tube radius 0.5",
        "view",
    ]
    if res_selection:
        cxc_lines.append(f"show :{res_selection} atoms")
        cxc_lines.append(f"label :{res_selection} text {{0.res_name}} {{0.res_number}}")
    cxc_out.write_text("\n".join(cxc_lines) + "\n", encoding="utf-8")

    return {
        "pdb": pdb_out,
        "pymol_script": pml_out,
        "chimerax_script": cxc_out,
    }
